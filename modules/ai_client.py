"""AI provider integration, isolated from the UI and from the safety/recommendation logic.

Swap providers by implementing `AIProvider.complete`. Nothing here decides what is safe.
API keys come from environment variables or Streamlit secrets only (see config.py).
"""
from __future__ import annotations

import json
from typing import Any, Protocol

import config

SYSTEM_PROMPT = """You are the writing voice of "Herbal Wellness AI". Speak like a strict, careful, professional herbalist taking a patient history: courteous but exacting, never flattering, never rushing to advise, always insisting on complete information before any suggestion.

You do NOT decide what is safe or what to recommend. A deterministic safety engine has already decided. You only write short, warm, plain-language text about the facts you are given.

Hard rules:
- Mention only the herbs listed in "approved_herbs" (and any in "user_mentioned_herbs"). Never introduce any other herb, supplement, product, oil, dose, or brand.
- Never diagnose, never promise a cure or guaranteed result, never say "natural means safe".
- Never give doses or amounts. Never tell anyone to stop or change prescribed medicine, or to delay seeing a clinician.
- Be honest about evidence: use the supplied evidence labels; say "traditionally used" for traditional-only evidence.
- Do not invent facts, studies, products or prices. If something is not in the provided data, say it is not known.
- Do not repeat questions the user already answered. Do not ask your own questions; questions are added separately.
- Keep it under 120 words unless asked for more. No HTML, no links, no tables.

Respond with ONE JSON object and nothing else:
{"message": "<your text>", "mentioned_herbs": ["<herb id>", ...]}
"mentioned_herbs" must list the ids of every herb named in your message (empty list if none)."""


class AIError(Exception):
    """Raised for any model/API problem. `user_message` is safe to show to the user."""

    def __init__(self, kind: str, user_message: str):
        super().__init__(user_message)
        self.kind = kind
        self.user_message = user_message


class AIProvider(Protocol):
    def complete(self, system: str, user_payload: str, max_tokens: int, timeout: float) -> str: ...


class AnthropicProvider:
    """Uses the official `anthropic` SDK (Messages API)."""

    def __init__(self, api_key: str, model: str):
        self.api_key = api_key
        self.model = model

    def complete(self, system: str, user_payload: str, max_tokens: int, timeout: float) -> str:
        try:
            import anthropic
        except ImportError as exc:  # pragma: no cover
            raise AIError("missing_sdk", "The 'anthropic' package is not installed. Run: pip install -r requirements.txt") from exc
        client = anthropic.Anthropic(api_key=self.api_key, timeout=timeout, max_retries=1)
        try:
            resp = client.messages.create(
                model=self.model, max_tokens=max_tokens, system=system,
                messages=[{"role": "user", "content": user_payload}],
            )
        except anthropic.APITimeoutError as exc:
            raise AIError("timeout", "The AI service took too long to respond. Please try again.") from exc
        except anthropic.RateLimitError as exc:
            raise AIError("rate_limit", "The AI service is busy (rate limit reached). Please wait a moment and try again.") from exc
        except anthropic.AuthenticationError as exc:
            raise AIError("auth", "The API key was rejected. Check ANTHROPIC_API_KEY in your .env file.") from exc
        except anthropic.APIConnectionError as exc:
            raise AIError("network", "Could not reach the AI service. Check your internet connection.") from exc
        except anthropic.APIStatusError as exc:
            raise AIError("api_error", f"The AI service returned an error (status {getattr(exc, 'status_code', '?')}). Please try again later.") from exc
        parts = [getattr(b, "text", "") for b in resp.content if getattr(b, "type", "") == "text"]
        return "".join(parts)


NO_KEY_MESSAGE = (
    "No AI model is configured, so Herbal Wellness AI is running in **guided mode**: the questions, safety checks and "
    "recommendations still work from the local knowledge base, but replies are template-based, not generated by an AI model. "
    "To enable AI replies, set ANTHROPIC_API_KEY (copy .env.example to .env, or use Streamlit secrets) and restart the app."
)


class AIClient:
    def __init__(self, provider: AIProvider | None = None, api_key: str | None = None, model: str | None = None):
        if provider is not None:
            self._provider: AIProvider | None = provider
        else:
            key = api_key if api_key is not None else config.api_key()
            self._provider = AnthropicProvider(key, model or config.model_name()) if key else None

    @property
    def configured(self) -> bool:
        return self._provider is not None

    def status_message(self) -> str:
        return "AI model configured." if self.configured else NO_KEY_MESSAGE

    def complete_json(self, task: str, context: dict[str, Any]) -> str:
        """Send a structured task to the model. Returns raw text (validated elsewhere)."""
        if self._provider is None:
            raise AIError("not_configured", NO_KEY_MESSAGE)
        payload = json.dumps({"task": task, **context}, ensure_ascii=False)
        return self._provider.complete(SYSTEM_PROMPT, payload, config.max_tokens(), config.timeout_seconds())

    def consult(self, context: dict[str, Any]) -> str:
        """Herbalist consultation call: persona + examples as the system prompt, the patient context as the payload."""
        if self._provider is None:
            raise AIError("not_configured", NO_KEY_MESSAGE)
        from modules import herbalist_prompt
        payload = json.dumps(context, ensure_ascii=False)
        return self._provider.complete(herbalist_prompt.system_prompt(), payload,
                                       config.herbalist_max_tokens(), config.herbalist_timeout_seconds())
